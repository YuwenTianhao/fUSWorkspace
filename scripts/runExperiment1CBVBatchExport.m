% Export all 16 sections from experiment 1 through fUSWorkspaceAppV2.
projectRoot = fileparts(fileparts(mfilename("fullpath")));
sourceRoot = "D:\Tianhao\YWTH_fus4D_20260917\converted_pdi\group_01";
planFile = fullfile(sourceRoot, "experiment_plan.csv");
outputRoot = fullfile(sourceRoot, ...
    "mp4_test_baseline_0_150s_range25_alpha30_nomask_2fps");

addpath(fullfile(projectRoot, "app"), fullfile(projectRoot, "core"));
if isfolder(outputRoot)
    existing = dir(outputRoot);
    existing = existing(~ismember({existing.name}, {'.', '..'}));
    if ~isempty(existing)
        error("fUSWorkspace:BatchOutputNotEmpty", ...
            "Output folder is not empty; refusing to overwrite: %s", outputRoot);
    end
else
    mkdir(outputRoot);
end

sections = dir(fullfile(sourceRoot, "section_*_pose_*_plane_*"));
sections = sections([sections.isdir]);
[~, order] = sort({sections.name});
sections = sections(order);
if numel(sections) ~= 16
    error("fUSWorkspace:UnexpectedSectionCount", ...
        "Expected 16 experiment-1 sections but found %d.", numel(sections));
end

app = fUSWorkspaceAppV2();
appCleanup = onCleanup(@()delete(app));
app.getFigure().Visible = "off";
result = table('Size', [numel(sections), 8], ...
    'VariableTypes', ["double", repmat("string", 1, 3), repmat("double", 1, 4)], ...
    'VariableNames', ["Section", "SectionFolder", "VideoFile", "SettingsFile", ...
        "FrameCount", "VideoFrameRate", "Duration_s", "Bytes"]);

for index = 1:numel(sections)
    sectionFolder = string(fullfile(sections(index).folder, sections(index).name));
    videoName = string(sections(index).name) + "_CBV.mp4";
    outputPath = fullfile(outputRoot, videoName);
    fprintf("[%s] Exporting %d/%d: %s\n", ...
        char(datetime("now", Format="HH:mm:ss")), ...
        index, numel(sections), sections(index).name);
    videoExport = app.batchExportCBVVideo(sectionFolder, outputPath, ...
        ActualFPS=5/12, ...
        BaselineSeconds=[0, 150], ...
        DisplayLimit=25, ...
        Transparency=0.30, ...
        BrainMask=false, ...
        LowThreshold=0, ...
        ShowBackground=true, ...
        VideoFrameRate=2, ...
        ExperimentPlanFile=planFile);
    fileInfo = dir(outputPath);
    settingsPath = fullfile(outputRoot, ...
        erase(videoName, ".mp4") + "_settings.mat");
    result(index, :) = {index, sectionFolder, string(outputPath), ...
        string(settingsPath), videoExport.FrameCount, ...
        videoExport.VideoFrameRate, ...
        videoExport.FrameCount/videoExport.VideoFrameRate, fileInfo.bytes};
    writetable(result(1:index, :), fullfile(outputRoot, "export_summary.csv"));
    fprintf("[%s] Completed %d/%d: %.2f MB\n", ...
        char(datetime("now", Format="HH:mm:ss")), ...
        index, numel(sections), fileInfo.bytes/1024/1024);
end

clear appCleanup
fprintf("Export complete: %d videos, %.2f MB total\n", ...
    height(result), sum(result.Bytes)/1024/1024);
disp(result(:, ["Section", "VideoFile", "FrameCount", "Duration_s", "Bytes"]));
