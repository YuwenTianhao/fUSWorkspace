% Export spatially ordered CBV MP4 files for YWTH experiments 2 through 8.
projectRoot = fileparts(fileparts(mfilename("fullpath")));
convertedRoot = "D:\Tianhao\YWTH_fus4D_20260917\converted_pdi";
addpath(fullfile(projectRoot, "app"), fullfile(projectRoot, "core"));

groups = (2:8).';
baselineEndSeconds = [150; 600; 150; 270; 150; 150; 150];
displayLimit = 25;
transparency = 0.30;
videoFrameRate = 2;
actualFPS = 5/12;

result = table('Size', [numel(groups)*16, 13], ...
    'VariableTypes', [repmat("double", 1, 4), repmat("string", 1, 3), ...
        repmat("double", 1, 5), "string"], ...
    'VariableNames', ["Group", "SpatialOrder", "OriginalSection", ...
        "AxisPosition_mm", "SectionFolder", "VideoFile", "SettingsFile", ...
        "BaselineEnd_s", "FrameCount", "VideoFrameRate", "Duration_s", ...
        "Bytes", "Status"]);
resultRow = 0;

app = fUSWorkspaceAppV2();
appCleanup = onCleanup(@()delete(app));
app.getFigure().Visible = "off";

for groupIndex = 1:numel(groups)
    groupNumber = groups(groupIndex);
    baselineEnd = baselineEndSeconds(groupIndex);
    groupRoot = fullfile(convertedRoot, sprintf("group_%02d", groupNumber));
    planFile = fullfile(groupRoot, "experiment_plan.csv");
    sectionManifestPath = fullfile(groupRoot, "section_manifest.csv");
    if ~isfile(planFile) || ~isfile(sectionManifestPath)
        error("fUSWorkspace:BatchGroupMetadataMissing", ...
            "Group %d is missing its plan or section manifest.", groupNumber);
    end

    outputRoot = fullfile(groupRoot, sprintf( ...
        "mp4_position_ordered_baseline_0_%ds_range25_alpha30_nomask_2fps", ...
        baselineEnd));
    if ~isfolder(outputRoot)
        mkdir(outputRoot);
    end

    sections = readtable(sectionManifestPath, TextType="string");
    sections.AxisPosition_mm = sections.PoseX_mm + sections.PlaneY_mm;
    sections = sortrows(sections, "AxisPosition_mm");
    sections.SpatialOrder = (1:height(sections)).';
    if height(sections) ~= 16 ...
            || any(abs(diff(sections.AxisPosition_mm) - 0.525) > 1e-9)
        error("fUSWorkspace:UnexpectedSpatialSectionOrder", ...
            "Group %d does not contain 16 sections spaced by 0.525 mm.", ...
            groupNumber);
    end
    writetable(sections, fullfile(outputRoot, "spatial_order_manifest.csv"));

    fprintf("\n[%s] Group %d: baseline 0-%g s, exporting 16 sections\n", ...
        clockText(), groupNumber, baselineEnd);
    groupResultRows = zeros(16, 1);
    for spatialOrder = 1:height(sections)
        resultRow = resultRow + 1;
        groupResultRows(spatialOrder) = resultRow;
        sourceSection = double(sections.Section(spatialOrder));
        pose = double(sections.Pose(spatialOrder));
        plane = double(sections.Plane(spatialOrder));
        axisPosition = double(sections.AxisPosition_mm(spatialOrder));
        sectionFolder = fullfile(groupRoot, sections.Folder(spatialOrder));
        videoName = sprintf( ...
            "position_%02d_axis_%+.3fmm_section_%02d_pose_%02d_plane_%02d_CBV.mp4", ...
            spatialOrder, axisPosition, sourceSection, pose, plane);
        outputPath = fullfile(outputRoot, videoName);
        [~, baseName] = fileparts(videoName);
        settingsPath = fullfile(outputRoot, string(baseName) + "_settings.mat");

        fprintf("[%s] Group %d | %02d/16 | source section %02d | %+.3f mm\n", ...
            clockText(), groupNumber, spatialOrder, sourceSection, axisPosition);
        if isfile(outputPath) && isfile(settingsPath)
            videoExport = loadExistingExport(settingsPath, outputPath, ...
                actualFPS, baselineEnd, displayLimit, transparency, videoFrameRate);
            status = "existing-validated";
        elseif isfile(outputPath) || isfile(settingsPath)
            error("fUSWorkspace:IncompleteExistingBatchExport", ...
                "Only one of video/settings exists for %s.", outputPath);
        else
            videoExport = app.batchExportCBVVideo(sectionFolder, outputPath, ...
                ActualFPS=actualFPS, ...
                BaselineSeconds=[0, baselineEnd], ...
                DisplayLimit=displayLimit, ...
                Transparency=transparency, ...
                BrainMask=false, ...
                LowThreshold=0, ...
                ShowBackground=true, ...
                VideoFrameRate=videoFrameRate, ...
                ExperimentPlanFile=planFile);
            status = "exported";
        end

        fileInfo = dir(outputPath);
        result(resultRow, :) = {groupNumber, spatialOrder, sourceSection, ...
            axisPosition, string(sectionFolder), string(outputPath), ...
            string(settingsPath), baselineEnd, videoExport.FrameCount, ...
            videoExport.VideoFrameRate, ...
            videoExport.FrameCount/videoExport.VideoFrameRate, ...
            fileInfo.bytes, status};
        writetable(result(1:resultRow, :), ...
            fullfile(convertedRoot, "experiments_02_to_08_mp4_summary.csv"));
        writetable(result(groupResultRows(1:spatialOrder), :), ...
            fullfile(outputRoot, "export_summary.csv"));
    end
end

clear appCleanup
fprintf("\nExport complete: %d videos, %.2f MB total\n", ...
    height(result), sum(result.Bytes)/1024/1024);
disp(groupsummary(result, "Group", "sum", ["FrameCount", "Bytes"]));


function text = clockText()
text = char(datetime("now", Format="HH:mm:ss"));
end


function videoExport = loadExistingExport(settingsPath, outputPath, ...
    actualFPS, baselineEnd, displayLimit, transparency, videoFrameRate)
saved = load(settingsPath, "videoExport");
videoExport = saved.videoExport;
configuration = videoExport.Configuration;
valid = isfile(outputPath) ...
    && videoExport.OutputPath == string(outputPath) ...
    && videoExport.VideoFrameRate == videoFrameRate ...
    && configuration.ActualFPS == actualFPS ...
    && configuration.BaselineStart == 0 ...
    && configuration.BaselineEnd == baselineEnd ...
    && configuration.HighThreshold == displayLimit ...
    && configuration.LowThreshold == 0 ...
    && abs(configuration.Transparency - transparency) < 1e-12 ...
    && ~configuration.BrainMask ...
    && configuration.ShowBackground;
if ~valid
    error("fUSWorkspace:ExistingBatchExportMismatch", ...
        "Existing export does not match requested settings: %s", outputPath);
end
end
