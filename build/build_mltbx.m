%% 将开发源码打包为 MATLAB Apps 页可安装的 MLTBX
buildFolder = fileparts(mfilename("fullpath"));
projectFolder = fileparts(buildFolder);
appVersion = strtrim(string(fileread(fullfile(projectFolder, "VERSION"))));
assert(~isempty(regexp(appVersion, '^\d+\.\d+\.\d+$', 'once')), ...
    "VERSION必须是三段版本号，例如1.5.2。");
appFolder = fullfile(projectFolder, "app");
coreFolder = fullfile(projectFolder, "core");
iconFolder = fullfile(projectFolder, "assets", "icons");
releaseFolder = fullfile(projectFolder, "release");
if ~isfolder(releaseFolder)
    mkdir(releaseFolder);
end

entryFile = fullfile(appFolder, "fUSWorkspaceMatlabApp.m");
controllerFile = fullfile(appFolder, "fUSWorkspaceAppV2.m");
layoutFile = fullfile(appFolder, "fUSWorkspaceLayout.m");
coreEntries = dir(fullfile(coreFolder, "**", "*.m"));
coreFiles = string(fullfile({coreEntries.folder}, {coreEntries.name}));
readmeFile = fullfile(projectFolder, "README.md");
migrationGuide = fullfile(projectFolder, "docs", "AppDesigner迁移指南.md");
sourceGuide = fullfile(projectFolder, "docs", "源码导航.md");
algorithmGuide = fullfile(projectFolder, "docs", "如何添加新算法.md");
desktopToolset = fullfile(projectFolder, "DesktopToolset.xml");
% 运行包只携带实际使用的尺寸；master和128像素版本保留给后续制图。
iconFiles = [ ...
    fullfile(iconFolder, "fUSWorkspace_AppIcon_16.png"), ...
    fullfile(iconFolder, "fUSWorkspace_AppIcon_24.png"), ...
    fullfile(iconFolder, "fUSWorkspace_AppIcon_256.png")];
% Apps 栏从安装包的注册目录加载图标；同时在两个可能的相对基目录放置图标。
galleryIconFiles = strings(1, 4);
galleryIconFolders = [ ...
    fullfile(projectFolder, "resources", "assets", "icons"), ...
    fullfile(appFolder, "assets", "icons")];
galleryIconNames = ["fUSWorkspace_AppIcon_16.png", "fUSWorkspace_AppIcon_24.png"];
k = 0;
for folder = galleryIconFolders
    if ~isfolder(folder)
        mkdir(folder);
    end
    for name = galleryIconNames
        k = k + 1;
        galleryIconFiles(k) = fullfile(folder, name);
        copyfile(fullfile(iconFolder, name), galleryIconFiles(k));
    end
end
toolboxImage = fullfile(iconFolder, "fUSWorkspace_AppIcon_256.png");
examplePlans = [ ...
    fullfile(projectFolder, "examples", "experiment_plan_example.csv"), ...
    fullfile(projectFolder, "examples", "experiment_plan_hindpaw_240s.csv")];
outputFile = fullfile(releaseFolder, "fUSWorkspace_" + appVersion + ".mltbx");

opts = matlab.addons.toolbox.ToolboxOptions( ...
    projectFolder, "b2d1c2a4-7f17-4d76-bda2-20260820f001", ...
    ToolboxName="fUS Workspace", ...
    ToolboxVersion=appVersion, ...
    Summary="PDI/BMP/PNG浏览、多ROI CBV曲线分析与MP4导出", ...
    Description="支持Marsonics PDI线性数据、BMP/PNG显示图及多边形ROI CBV分析的fUS工作区。", ...
    AuthorName="Tianhao Yuwen", ...
    ToolboxImageFile=toolboxImage, ...
    ToolboxFiles=[entryFile, controllerFile, layoutFile, coreFiles, ...
        desktopToolset, iconFiles, galleryIconFiles, readmeFile, migrationGuide, sourceGuide, ...
        algorithmGuide, examplePlans], ...
    AppGalleryFiles=entryFile, ...
    ToolboxMatlabPath={projectFolder, appFolder, coreFolder}, ...
    MinimumMatlabRelease="R2025a", ...
    OutputFile=outputFile);

matlab.addons.toolbox.packageToolbox(opts);
fprintf("已生成：%s\n", outputFile);
